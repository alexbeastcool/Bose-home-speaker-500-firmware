/**
 * Handles any message recieved by WebSocket
 * @param {object} payload
 */
function socketMessage(payload) {

    var msgObj = JSON.parse(payload.data);

    if (msgObj.header) {

        var action = msgObj.header.resource;

        // we are only interested in specific types of messages
        switch (action) {
            case '/system/info':
                device = msgObj.body;
                // account for correct definition 'guid' and incorrect definition 'GUID'
                // TODO: remove 'GUID'
                guid = msgObj.body.guid || msgObj.body.GUID;
                // Get AP network name, which we will use later to shut down AP network
                socketSend('GET', '/network/wifi/ap');
                break;
            case '/network/wifi/siteScan':
            case '/network/status':
                if (!success) {
                    if (msgObj.body && msgObj.body.wifiScanResult && msgObj.header.reqID === getNetworksReqID) {
                        parseNetworks(msgObj);
                    }
                }
                else {
                    // Get new IP address after successful connection
                    var connectedIpInfo = msgObj.body.interfaces.filter(function (obj) {
                        return obj.name === "wlan0";
                    });
                    deviceIp = connectedIpInfo[0].ipInfo.ipAddress;
                }
                break;
            case '/network/wifi/profile':
                if (msgObj.header.reqID === wifiProfileReqID) {
                    parseConnectToNetworkResponse(msgObj.body);
                }
                break;
            case '/network/wifi/ap':
                if (msgObj) {
                    ap_name = msgObj.body.name;
                }
                break;
            case '/productDiscovery/info':
                if (msgObj.body && msgObj.body.capabilities && Array.isArray(msgObj.body.capabilities.supportedWifiBands)) {
                supportedWifiBands = msgObj.body.capabilities.supportedWifiBands;
                console.log("supported wifi bands of current device:" + JSON.stringify(supportedWifiBands))
                }
                break;
            default:
                break;
        }
    }

}

/**
 * Sends a message to a specified endpoint path
 * @param {object} payload
 */
function socketSend(method, path, body) {
    reqID++;
    var sendObj = {};

    //define the header
    var headerObj = {};
    headerObj.resource = path || "";
    headerObj.token = DEVICE_TOKEN || "";
    headerObj.msgtype = 'REQUEST';
    headerObj.method = method || "";
    headerObj.device = guid || "";
    headerObj.reqID = reqID;

    sendObj.header = headerObj;

    //if payload is defined and not an empty string, define it as the body
    if (body && body.trim().length > 0) {
        try {
            var bodyObj = JSON.parse(body);
            sendObj.body = bodyObj;
        }
        catch (err) {
            alert('Error parsing outgoing JSON. See JS console for more details');
            throw new Error('Unable to parse outgoing body JSON: ' + err);
        }
    }

    var sendStr;
    try {
        sendStr = JSON.stringify(sendObj);
    }
    catch (err) {
        console.log('Unable to parse outgoing payload JSON: ' + err);
    }

    try {
        ws.send(sendStr);
        console.log('sending network request message for_' + path + '_message:_' + sendStr)
        return reqID;
    }
    catch (err) {
        console.log("Couldn't send message: " + err);
        console.log("Couldn't send message to : " + path);
        return -1;
    }
}

/**
 * Attempt to send an info request to speaker to open the websocket.
 * May not be necessary, but occasionally a WS needs a message sent to it
 * in order to become active
 *
 * Also used to get the guid
 */
function requestSysInfoToOpenWebSocket() {

    var sysInfoReqId = socketSend('GET', '/system/info');
    //if unable to send, retry in 1500 ms
    if (sysInfoReqId === -1) {

        if (numGetSysInfoRetries > 0) {

            numGetSysInfoRetries--;
            setTimeout(requestSysInfoToOpenWebSocket, 1500);

        } else {

            console.warn('Unable to request systemInfo; Websocket may not be open');

        }

    }

}

