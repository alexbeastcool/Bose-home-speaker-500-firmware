/**
 * Parse URL params for use in pre-populating input fields
 * and navigating back to other Bose applications
*/
function parseUrlParams() {

    var queryParams = decodeURIComponent(window.location.search);
    var queryArray = queryParams.length > 0 ? queryParams.split("?")[1].split("&") : [];

    for (var i = 0; i < queryArray.length; ++i) {
        var keyValueArray = queryArray[i].split("=");
        queryParamsObj[keyValueArray[0]] = keyValueArray[1];
    }
}

/**
 * Parses an object of avaialble WiFi networks into
 * UI elements
 * @param {object} networkPayload - networks object
 */
function parseNetworks(networkPayload) {

    networks = [];

    var tmpArr = networkPayload.body.wifiScanResult;

    if (tmpArr && tmpArr.length > 0) {
        for (i = 0; i < tmpArr.length; i++) {
            var tmpNet = [];
            var thisNetArr = tmpArr[i];

            tmpNet[0] = thisNetArr.ssid; //name
            tmpNet[1] = thisNetArr.signalDbm; //strength
            tmpNet[2] = thisNetArr.security; //security
            tmpNet[3] = thisNetArr.frequencyKhz; //network band frequency
            tmpNet[4] = tmpNet.ssid; //full name
            tmpNet[5] = null; //cipher
            
            //determining the band from frequency
            var freq = tmpNet[3];
            var band = null;

            if (freq >= BAND_2_4_GHZ_RANGE.min && freq <= BAND_2_4_GHZ_RANGE.max) {
            band = BAND_2_4_GHZ;
            } else if (freq >= BAND_5_GHZ_RANGE.min && freq <= BAND_5_GHZ_RANGE.max) {
            band = BAND_5_GHZ;
            } else if (freq >= BAND_6_GHZ_RANGE.min && freq <= BAND_6_GHZ_RANGE.max) {
            band = BAND_6_GHZ;
            }

            // Only filter if supportedWifiBands has actual values
            if (Array.isArray(supportedWifiBands) && supportedWifiBands.length > 0 && band && !supportedWifiBands.includes(band)) continue;

            if (tmpNet[0] == '') { } // do not add blank string
            else if (tmpNet[0].substr(0, 5) == 'Bose ') { } // do not add Bose network and do not break from loop
            else if (networks.length > 0 && networks[networks.length - 1][0] == tmpNet[0] && networks[networks.length - 1][2] == tmpNet[2]) { } 	//de-dupe
            else
                networks.push(tmpNet);
        }

        updateWifiList();
    }
    else {
        getNetworks();
    }
}

/**
 * Called on wifi credentials form submit
 * Parses the Wifi network credentials and sends them
 * to the device
 */
var sendProfileObj =
{
    "security": "",
    "ssid": "",
    "passphrase": ""
};
function parseSubmitWifiForm() {

    var curNet = document.getElementById('ssids').selectedIndex || 0;
    var curPass = document.getElementById('password_default').value || 0;
    var curSec = document.getElementById('security').value;

    if (!showManualForm) {
        curSec = networks[curNet][2];
    }

    sendProfileObj.security = curSec;

    var sanitizedCurSec = curSec ? curSec.toLowerCase() : "none";

    // for regular setup
    if (!showManualForm) {
        sendProfileObj.ssid = networks[curNet][0];
    }

    // for manual setup
    else {
        sendProfileObj.ssid = document.getElementById('netName').value;
        sendProfileObj.passphrase = document.getElementById('password_manual').value;
    }

    selected_ssid = sendProfileObj.ssid;
    document.getElementById('NETWORK_NAME').textContent = selected_ssid;

    // handles security for regular and manual setup in case security exists
    if (sanitizedCurSec !== "none" && !showManualForm) {
        sendProfileObj.passphrase = document.getElementById('password_default').value
    }

    // in case of no security - no need for password
    else if (sanitizedCurSec != "none" && showManualForm) {
        sendProfileObj.passphrase = document.getElementById('password_manual').value;
    }
    else {
        sendProfileObj.passphrase = "";
    }

    // Check for form errors before proceeding
    var err = '';
    if (!showManualForm) {
        // If network has security, make sure a password has been entered
        if (sanitizedCurSec !== 'none' && !sendProfileObj.passphrase) {
            err = translationsObj['ERROR_NO_PASSWORD'];
        }
    } else {
        // If network has security, make sure a password has been entered
        if (sanitizedCurSec !== 'none' && !sendProfileObj.passphrase) {
            err = translationsObj['ERROR_NO_PASSWORD'];
        }

        // Make sure a network has been entered
        if (!sendProfileObj.ssid) {
            err = translationsObj['ERROR_NO_NETWORK'];
        }
    }

    // If there's a form error, show error message and don't submit credentials
    if (err) {
        showErrorMessage(err);
        return;
    }

    if (!sendProfileObj.passphrase) {
        showPane('unsecured');
    } else {
        showPane('connecting');
        submitNetworkCreds(sendProfileObj);
    }

}

