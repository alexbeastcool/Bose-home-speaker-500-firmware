/*
 * Populate text based on language
 */
function populateText() {
    var lang = getLanguage();
    var langString = 'lang_' + lang;
    translationsObj = LANG_OBJ[langString];

    //If not exists, default to en
    if(!translationsObj) {
        translationsObj = LANG_OBJ['lang_en'];
    }
        
    var keys = Object.keys(translationsObj);
    // Iterate through translations and add to the corresponding divs,
    // except for error messages. They don't have their own divs.
    for (var i = 0; i < keys.length; i++) {
        if (keys[i].split('_')[0] !== 'ERROR') {
            el('#' + keys[i]).textContent = translationsObj[keys[i]];
        }
    }
}

/*
 * Get language from browser and parse. Default is 'en'.
 */
function getLanguage() {
    var userLang = window.navigator.userLanguage || window.navigator.language;
    var langRegex =  new RegExp(/[a-z]{2}(?:-[A-Z]{2})?$/);
    var isValidLang = langRegex.test(userLang);

    if (!isValidLang) {
        return 'en';
    }

    var curLang;
    var lang = userLang.split('-');

    if (lang.length > 1 && lang[0].toLowerCase() === 'zh') {
        if (lang[1].toLowerCase() === 'cn' || lang[1].toLowerCase() === 'sg') {
            curLang = 'zh_hans';
        } else {
            curLang = 'zh_hant';
        }
    } else {
        curLang = lang[0].toLowerCase();

        if (curLang === 'zh') {
            curLang = 'zh_hans';
        }
    }

    return curLang;

}
