/**
 * Target an element jQuery-style
 */
function el(name) {
    return document.querySelector(name);
}

/**
 * Show selected element
 */
function show(element) {
    if (!element.classList.contains('show')) {
        element.classList.add('show');
    }
    if (element.classList.contains('hide')) {
        element.classList.remove('hide');
    }
}

/**
 * Hide selected element
 */
function hide(element) {
    if (!element.classList.contains('hide')) {
        element.classList.add('hide');
    }
    if (element.classList.contains('show')) {
        element.classList.remove('show');
    }
}

/**
 * Fade in selected element
 */
function fadeIn(element) {
    element.classList.add('fade');
    element.classList.add('opacity-0');
    element.classList.remove('hide');
    element.classList.remove('show');
    setTimeout(function () {
        element.classList.add('opacity-1');
        cleanupTransition(element, 'show', 500);
    }, 500);

}

/**
 * Fade out selected element
 */
function fadeOut(element) {
    element.classList.add('fade');
    element.classList.add('opacity-1');
    element.classList.remove('show');
    setTimeout(function () {
        element.classList.add('opacity-0');
        cleanupTransition(element, 'hide', 100);
    }, 500);
}

/**
 * Since we're using opacity to fade and can't use show and hide classes,
 * we want to make sure we go back to using show and hide classes after fade ends
 */
function cleanupTransition(element, status, ms) {
    setTimeout(function () {
        element.classList.remove('fade');
        element.classList.remove('opacity-1');
        element.classList.remove('opacity-0');

        if (status === 'show') {
            element.classList.add('show');
        }

        if (status === 'hide') {
            element.classList.add('hide');
        }
    }, ms);
}

