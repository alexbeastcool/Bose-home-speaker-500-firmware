/**
 * Parses a response form the profiles endpoint to determine if we successfully
 * connected to the given WiFi network
 * @param {object} msgObj
 */
function parseConnectToNetworkResponse(msgObj) {

    var result = msgObj.result;

    if (result === 'WIFI_ADD_SUCCEEDED') {

        success = true;

        console.warn('WIFI_ADD_SUCCEEDED');
        if (waitedThreeSecs) {
            connectedSuccess();
        }
        else {
            setTimeout(function () {
                connectedSuccess();
            }, 3000);
        }
    }
    else {

        console.warn('WIFI_ADD_FAILED');
        showPane('setup');

        var reason = msgObj.reason;

        // If reason for failure is authentication, set the error as incorrect password
        if(reason === 'AUTHENTICATION_FAILED') 
            showErrorMessage(translationsObj['ERROR_INCORRECT_PASSWORD']);
        else
            showErrorMessage(translationsObj['ERROR_CONNECTION_FAILED']);

    }

}

