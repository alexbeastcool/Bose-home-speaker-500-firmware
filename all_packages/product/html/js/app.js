/**
 * Updates the list of available Wifi networks
 * and displays them
 */
function updateWifiList() {
    curType = "normal";
    var optionStr = '';

    for (var i = 0; i < networks.length; i++) {

        var escapedNetworkName = HTMLtext_escape(networks[i][0]);

        optionStr += '<option value="' + i + '"';

        // if this network name matches the network that was passed in via url params
        //set this value as the default in the newtwork selection element
        if (escapedNetworkName === queryParamsObj.ssid) {

            optionStr += ' selected="selected"'

        }

        optionStr += '>' + HTMLtext_escape(networks[i][0]);
        optionStr += '</option>';
    }

    el('#ssids').innerHTML = optionStr;

    if (!pageLoaded) {
        populateText();
        populateDeviceInfo();
    }

    if (!document.getElementById('setup').classList.contains('show')) {
        showPane('setup');
    }

}

/**
 * Escapes '<' and '>' chars
 * @param {string} str
 */
function HTMLtext_escape(str) {
    return str.replace("<", "&lt;").replace(">", "&gt;");
}

